import streamlit as st
import pandas as pd
import os
import time

st.set_page_config(page_title="Crypto Streams", page_icon="⚡", layout="wide")
st.title("⚡ Real-Time Market Arbitrage Dashboard")
st.markdown("_Consuming live Parquet data generated by PySpark Stream-to-Stream Joins_")

# Create a placeholder container for the auto-refreshing UI
placeholder = st.empty()
parquet_dir = "data/output/crypto_ratio"

while True:
    with placeholder.container():
        # 1. Check if the directory and parquet files exist yet
        if not os.path.exists(parquet_dir) or not any(f.endswith('.parquet') for f in os.listdir(parquet_dir)):
            st.info("Waiting for PySpark to write the first batch... (This takes ~60 seconds due to the watermark)")
        else:
            try:
                # 2. Read the Parquet data lake
                df = pd.read_parquet(parquet_dir)
                
                # 3. Check if the dataframe is empty
                if df.empty:
                    st.warning("Data Lake connected, waiting for matching BTC/ETH trades...")
                else:
                    # Sort by time and get the latest 100 joined events
                    df = df.sort_values("btc_time").tail(100)
                    
                    latest_btc = df['btc_price'].iloc[-1]
                    latest_eth = df['eth_price'].iloc[-1]
                    latest_ratio = df['btc_eth_ratio'].iloc[-1]

                    # KPI Metrics
                    col1, col2, col3 = st.columns(3)
                    col1.metric("Latest BTC Price", f"${latest_btc:,.2f}")
                    col2.metric("Latest ETH Price", f"${latest_eth:,.2f}")
                    col3.metric("BTC/ETH Ratio", f"{latest_ratio:.4f}")
                    
                    st.divider()
                    
                    # Live Charts
                    st.markdown("### Live Market Trends")
                    col_chart1, col_chart2, col_chart3 = st.columns(3)
                    
                    with col_chart1:
                        st.caption("Bitcoin (BTC) Price")
                        st.line_chart(df.set_index("btc_time")['btc_price'])
                        
                    with col_chart2:
                        st.caption("Ethereum (ETH) Price")
                        st.line_chart(df.set_index("btc_time")['eth_price'])
                        
                    with col_chart3:
                        st.caption("BTC/ETH Ratio")
                        st.line_chart(df.set_index("btc_time")['btc_eth_ratio'])
                        
            except Exception as e:
                # Catch read-lock errors when Spark is actively writing to the file
                st.warning("Syncing latest micro-batch with Data Lake...")
                
    # Wait 2 seconds, then force Streamlit to rerun and pull new data
    time.sleep(2)
    st.rerun()